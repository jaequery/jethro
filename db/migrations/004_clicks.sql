-- Visitor clicks on the public library (POST /api/clicks), one row per click.
-- `target` is a stable key for the clicked item ("site:<id>", "filter:industry=Fintech",
-- "out:stripe.com", ...) and `label` the text it showed. No visitor identity is kept.
CREATE TABLE clicks (
  id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  target  TEXT NOT NULL,
  label   TEXT,
  view    TEXT,
  site_id TEXT,
  at      TEXT NOT NULL
);

CREATE INDEX clicks_at ON clicks(at);
CREATE INDEX clicks_target ON clicks(target);
